const { initializeApp } = require('firebase/app');
const { getFirestore, collection, getDocs, doc, deleteDoc, addDoc } = require('firebase/firestore');
const { eachMonthOfInterval, format, parseISO, subMonths, addMonths } = require('date-fns');
const dotenv = require('dotenv');
const path = require('path');

dotenv.config({ path: path.resolve(__dirname, '../.env.local') });

const firebaseConfig = {
  apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY,
  authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN,
  projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID,
  storageBucket: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET,
};

const app = initializeApp(firebaseConfig);
const db = getFirestore(app);

const randInt = (min, max) => Math.floor(Math.random() * (max - min + 1)) + min;

async function fixAllTnmMilestones() {
  try {
    const projectsSnapshot = await getDocs(collection(db, 'projects'));
    console.log(`Checking ${projectsSnapshot.size} projects...`);
    
    const todayStr = new Date().toISOString().split('T')[0];

    for (const projectDoc of projectsSnapshot.docs) {
      const projectData = projectDoc.data();
      const projectId = projectDoc.id;
      
      // We check if the pricingModel is T&M (case-insensitive or containing T&M)
      const isTnm = projectData.pricingModel === 'T&M' || projectData.pricingModel === 'Time & Materials';
      
      if (!isTnm) {
        console.log(`- Project [${projectId}]: "${projectData.name}" is Fixed Bid. Skipping...`);
        continue;
      }

      console.log(`\n- Found T&M Project [${projectId}]: "${projectData.name}"`);
      
      // Determine project active months
      let selectableMonths = [];
      if (!projectData.startDate || !projectData.endDate) {
        const today = new Date();
        const start = subMonths(today, 6);
        const end = addMonths(today, 6);
        selectableMonths = eachMonthOfInterval({ start, end });
      } else {
        try {
          const start = parseISO(projectData.startDate);
          const end = parseISO(projectData.endDate);
          if (isNaN(start.getTime()) || isNaN(end.getTime()) || end < start) {
            const today = new Date();
            selectableMonths = eachMonthOfInterval({ start: subMonths(today, 6), end: addMonths(today, 6) });
          } else {
            selectableMonths = eachMonthOfInterval({ start, end });
          }
        } catch (e) {
          const today = new Date();
          selectableMonths = eachMonthOfInterval({ start: subMonths(today, 6), end: addMonths(today, 6) });
        }
      }

      const activeMonthsFormatted = selectableMonths.map(m => format(m, 'MMMM yyyy'));
      console.log(`  Active months calculated (${activeMonthsFormatted.length}): ${activeMonthsFormatted.join(', ')}`);

      const milestonesColRef = collection(db, 'projects', projectId, 'paymentMilestones');
      
      // Delete old milestones
      const pmSnapshot = await getDocs(milestonesColRef);
      console.log(`  Deleting ${pmSnapshot.size} existing milestones...`);
      for (const pmDoc of pmSnapshot.docs) {
        await deleteDoc(doc(db, 'projects', projectId, 'paymentMilestones', pmDoc.id));
      }

      // Add new monthly milestones
      console.log(`  Populating new monthly milestones...`);
      for (let i = 0; i < activeMonthsFormatted.length; i++) {
        const monthName = activeMonthsFormatted[i];
        const milestoneId = `PM-${i + 1}`;
        // Random amount between 25000 and 75000 for realistic autogenerated testing
        const amount = randInt(25000, 75000);
        
        const newMilestone = {
          milestoneId,
          name: monthName,
          amount,
          billingPercentage: 0,
          status: 'TBD',
          attachments: '',
          statusHistory: [
            {
              status: 'TBD',
              date: todayStr
            }
          ]
        };
        
        await addDoc(milestonesColRef, newMilestone);
      }
      console.log(`  Successfully initialized month-based milestones for "${projectData.name}"!`);
    }
    
    console.log('\nAll T&M project milestones corrected and pre-populated successfully!');
  } catch (err) {
    console.error("Error correcting T&M milestones:", err.message);
  }
}

fixAllTnmMilestones().then(() => process.exit(0));
